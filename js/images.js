function _shapeFor(p, a) {
  const n = p.name.toLowerCase();
  const c = p.category;
  const pt = p.petType;
  if (c === "food") return pt === "cat" ? _can(a) : _pouch(a);
  if (c === "treats") {
    if (n.includes("churu") || n.includes("cream") || n.includes("catnip") && pt === "cat") return _tube(a);
    return _jar(a, "stick");
  }
  if (c === "hygiene") {
    if (n.includes("litter") || n.includes("pad") || n.includes("wipes")) return _box(a);
    return _bottle(a, false);
  }
  if (c === "grooming") {
    if (n.includes("brush") || n.includes("clipper") || n.includes("nail")) return _brush(a);
    return _bottle(a, true);
  }
  if (c === "toys") {
    if (n.includes("wand") || n.includes("feather")) return _wand(a);
    if (n.includes("rope") || n.includes("tug")) return _rope(a);
    return _ball(a);
  }
  if (c === "accessories") {
    if (n.includes("bowl") || n.includes("fountain")) return _bowl(a);
    if (n.includes("harness")) return _harness(a);
    if (n.includes("carrier") || n.includes("backpack")) return _backpack(a);
    if (n.includes("mat")) return _mat(a);
    return _bowl(a);
  }
  if (c === "vitamins") {
    if (n.includes("paste") || n.includes("gel")) return _tube(a);
    if (n.includes("powder") || n.includes("calcium")) return _jar(a, "round");
    return _bottlePills(a);
  }
  return _pouch(a);
}

